"""Fill the README's `## Call trace` block from a run_query trace (engine/out/query_<set>.md).
Request URLs only: the key travels in the X-Api-Key header and never appears; no Qloo response body is copied.
  python3 -I readme_trace.py --trace out/query_stl-cedric.md --readme ../README.md"""
import argparse, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unsaid.qloo import redact  # noqa: E402

START, END = "<!-- trace:start -->", "<!-- trace:end -->"
ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument("--trace", required=True)
ap.add_argument("--readme", required=True)
a = ap.parse_args()
lines = open(a.trace).read().splitlines()
status = next((l for l in lines if l.startswith("Status ")), "")
calls = re.search(r"(\d+) Qloo calls", status)
rows = []
grab = False
for l in lines:
    if l.startswith("| # | step |"):
        grab = True
        continue
    if grab and l.startswith("|---"):
        continue
    if grab and l.startswith("| "):
        c = [x.strip() for x in l.strip("|").split("|")]
        n, step, st, url = c[0], c[1], c[2], c[-1]
        rows.append("| %s | %s | %s | %s |" % (n, step, st, redact(url)))
    elif grab and rows:
        break
if not rows:
    sys.exit("no request table in %s" % a.trace)
block = [START, "",
         "%s requests, in order. Every one is a GET to `hackathon.api.qloo.com`; the key is sent only in the "
         "`X-Api-Key` header. Long ID lists are shortened to the first two plus a count. Generated by "
         "`engine/readme_trace.py` from the trace `run_query.py` writes to `engine/out/`."
         % (calls.group(1) if calls else len(rows)), "",
         "| # | step | status | request |", "|---|---|---|---|"] + rows + ["", END]
readme = open(a.readme).read()
if START not in readme or END not in readme:
    sys.exit("README has no %s ... %s block" % (START, END))
pre, rest = readme.split(START, 1)
post = rest.split(END, 1)[1]
import re  # noqa: E402
# pool member IDs come from Qloo's responses; the public README shows only how many were sent
out = re.sub(r"filter\.results\.entities=[0-9A-Fa-f,\-]+,…\(\+(\d+)",
             lambda m: "filter.results.entities=<%d pool IDs>" % (int(m.group(1)) + 2), "\n".join(block))
open(a.readme, "w").write(pre + out + post)
print("call trace: %d requests written to %s" % (len(rows), a.readme))
